def write_file(rel: str, content: str):
    path = os.path.join(ROOT, rel)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    # gofmt 规范化
    subprocess.run(["gofmt", "-w", path], check=True)
    print(f"wrote {rel} ({content.count(chr(10))} lines)")


