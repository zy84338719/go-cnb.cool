TAG_FIELD_OVERRIDE = {"Event": "Events", "RepoLabels": "Labels"}
TAG_FILE_OVERRIDE = {
    "mission-resources": "mission_resources",
    "NpcObservability": "npc_observability",
    "RepoCodeIssue": "repo_code_issue",
    "ArtifactSecurity": "artifact_security",
    "GitSettings": "git_settings",
    "KnowledgeBase": "knowledge_base",
    "RepoLabels": "repo_labels",
    "RepoContributor": "repo_contributor",
}
ARG_NAME_OVERRIDE = {"type": "pkgType"}


def tag_identifiers(tag: str):
    if tag == "AI":
        svc, field = "AIService", "AI"
    else:
        svc = pascal(tag) + "Service"
        field = TAG_FIELD_OVERRIDE.get(tag, pascal(tag))
    fname = TAG_FILE_OVERRIDE.get(
        tag, re.sub(r"(?<!^)(?=[A-Z])", "_", tag).lower())
    return svc, field, fname


def arg_name(raw: str) -> str:
    a = camel(raw)
    a = ARG_NAME_OVERRIDE.get(a, a)
    if a in GO_KEYWORDS or a in ("ctx", "body", "opts", "client", "s"):
        a += "_"
    return a


def perm_from_desc(desc: str) -> str:
    m = re.findall(r"\b([a-z][a-z0-9]*(?:-[a-z0-9]+)+:[rwd]+)\b", desc or "")
    return ", ".join(dict.fromkeys(m))


def path_params(o):
    return [p for p in o["params"] if p.get("in") == "path"]


def body_param(o):
    for p in o["params"]:
        if p.get("in") == "body":
            return p
    return None


def query_params(o):
    return [p for p in o["params"] if p.get("in") == "query"]


def find_response_schema(op: dict):
    for code, resp in op.get("responses", {}).items():
        if code.startswith("2"):
            return resp.get("schema")
    return None


ops_by_tag = defaultdict(list)
for o in ops:
    ops_by_tag[o["tag"]].append(o)

TAG_SERVICE = {t: tag_identifiers(t) for t in ops_by_tag}

used_aux_names = NameRegistry()
service_files = defaultdict(list)
aux_defs = []  # Options / 内联请求体


def gen_method(o):
    opid = o["opid"]
    op = o["op"]
    method = o["method"]
    svc = TAG_SERVICE[o["tag"]][0]

    pps = path_params(o)
    bps = body_param(o)
    qps = query_params(o)

    # 路径模板
    fmt_path = o["path"]
    args_sig = []
    fmt_args = []
    for p in pps:
        raw = p["name"]
        an = arg_name(raw)
        ptype = "int" if p.get("type") == "integer" else "string"
        args_sig.append(f"{an} {ptype}")
        verb = "%d" if ptype == "int" else "%s"
        fmt_path = fmt_path.replace("{" + raw + "}", verb)
        fmt_args.append(an)
    fmt_call = (f'escapePath("{fmt_path}"'
                + (", " + ", ".join(fmt_args) if fmt_args else "") + ")")

    # 查询参数 Options
    opt_type = None
    opt_fields = []
    has_pager = (any(p.get("name") == "page" for p in qps)
                 and any(p.get("name") == "page_size" for p in qps))
    for p in qps:
        nm = p.get("name")
        if has_pager and nm in ("page", "page_size"):
            continue
        if "$ref" in p:
            schema = {"$ref": p["$ref"]}
        else:
            schema = {k: v for k, v in p.items()
                      if k in ("type", "format", "enum", "items")}
        base, _ = go_type(schema, True)
        gt = base if (base.startswith("[]") or base.startswith("map[")) else "*" + base
        doc = clean_doc(p.get("description") or "")
        if p.get("enum"):
            allowed = ", ".join(str(e) for e in p["enum"])
            doc = (doc + " " if doc else "") + f"可选值: {allowed}."
        opt_fields.append((pascal(nm), gt, nm, doc))

    if opt_fields or has_pager:
        opt_type = used_aux_names.alloc(f"{opid}Options")
        olines = []
        doc = clean_doc(op.get("summary") or opid)
        olines.append(f"// {opt_type} {doc} 的查询参数.")
        olines.append(f"type {opt_type} struct {{")
        if has_pager:
            olines.append('\tListOptions `json:",inline"`')
        for gname, gt, tagname, doc in opt_fields:
            if doc:
                olines.append(f"\t// {gname} {doc}")
            olines.append(f'\t{gname} {gt} `json:"{tagname},omitempty"`')
        olines.append("}")
        aux_defs.append(olines)

    if opt_type:
        args_sig.append(f"opts *{opt_type}")

    # 请求体参数
    body_inline = None
    if bps:
        bs = bps.get("schema", {})
        if "$ref" in bs:
            btype = type_names[ref_name(bs)]
        else:
            btype = used_aux_names.alloc(f"{opid}Body")
            body_inline = (btype, bs)
        args_sig.append(f"body {btype}")

    # 返回值
    rs = find_response_schema(op)
    mlines = []
    summary = clean_doc(op.get("summary") or "")
    mlines.append(f"// {opid} {summary or opid}")
    perm = perm_from_desc(op.get("description") or "")
    if perm:
        mlines.append("//")
        mlines.append(f"// 访问令牌权限: {perm}")
    mlines.append("//")
    mlines.append(f"// CNB API: {method} {o['path']}")

    sig = f"func (s *{svc}) {opid}(ctx context.Context"
    if args_sig:
        sig += ", " + ", ".join(args_sig)

    if rs is None:
        sig += ") (*Response, error) {"
        err_vals = ("nil, err",)
        ok_vals = None
        out_decl = None
    elif "$ref" in rs:
        rt = type_names[ref_name(rs)]
        sig += f") (*{rt}, *Response, error) {{"
        err_vals = ("nil", "nil", "err")
        ok_vals = ("&out", "resp", "nil")
        out_decl = f"var out {rt}"
    elif rs.get("type") == "array":
        it = rs.get("items", {})
        if "$ref" in it:
            et = type_names[ref_name(it)]
            sig += f") ([]*{et}, *Response, error) {{"
            out_decl = f"var out []*{et}"
        else:
            st, _ = go_type(it, False)
            sig += f") ([]{st}, *Response, error) {{"
            out_decl = f"var out []{st}"
        err_vals = ("nil", "nil", "err")
        ok_vals = ("out", "resp", "nil")
    else:
        st, _ = go_type(rs, False)
        sig += f") (*{st}, *Response, error) {{"
        out_decl = f"var out {st}"
        err_vals = ("nil", "nil", "err")
        ok_vals = ("&out", "resp", "nil")

    mlines.append(sig)
    mlines.append(f"\tu := {fmt_call}")
    if opt_type:
        mlines.append("\tif opts != nil {")
        mlines.append("\t\tvar err error")
        mlines.append("\t\tu, err = addQuery(u, opts)")
        mlines.append("\t\tif err != nil {")
        mlines.append("\t\t\treturn " + ", ".join(err_vals[:2] if rs is None else err_vals))
        mlines.append("\t\t}")
        mlines.append("\t}")
    body_arg = "body" if bps else "nil"
    mlines.append(
        f"\treq, err := s.client.NewRequest(http.Method{method.title()}, u, {body_arg})")
    mlines.append("\tif err != nil {")
    mlines.append("\t\treturn " + (", ".join(err_vals[:2] if rs is None else err_vals)))
    mlines.append("\t}")
    if rs is None:
        mlines.append("\treturn s.client.Do(ctx, req, nil)")
    else:
        mlines.append(f"\t{out_decl}")
        mlines.append("\tresp, err := s.client.Do(ctx, req, &out)")
        mlines.append("\tif err != nil {")
        mlines.append("\t\treturn nil, resp, err")
        mlines.append("\t}")
        mlines.append("\treturn " + ", ".join(ok_vals))
    mlines.append("}")

    if body_inline:
        bname, bs = body_inline
        blines = [f"// {bname} {opid} 的请求体."]
        blines.append(f"type {bname} struct {{")
        for pn, p in sorted((bs.get("properties") or {}).items()):
            base, _ = go_type(p, True)
            gt = pointer_type(base, True)
            pd = clean_doc(p.get("description") or "")
            if pd:
                blines.append(f"\t// {pascal(pn)} {pd}")
            blines.append(f'\t{pascal(pn)} {gt} `json:"{pn},omitempty"`')
        if not bs.get("properties"):
            blines.append('\t_ struct{} `json:"-"`')
        blines.append("}")
        aux_defs.append(blines)

    return mlines


for o in ops:
    service_files[o["tag"]].append(gen_method(o))

