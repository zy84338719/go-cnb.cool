model_files = defaultdict(list)


def model_file_for(defname: str) -> str:
    prefix = defname.split(".")[0]
    if prefix in ("api", "dto", "openapi", "web", "constant"):
        return f"models_{prefix}_gen.go"
    return "models_misc_gen.go"


def gen_struct(defname: str) -> list:
    d = DEFS[defname]
    name = type_names[defname]
    req_style = defname in request_defs
    lines = []
    doc = clean_doc(d.get("description") or "")
    if doc:
        lines.append(f"// {name} {doc}")
    lines.append(f"type {name} struct {{")
    props = d.get("properties") or {}
    for pname in sorted(props):
        p = dict(props[pname])
        if "allOf" in p:
            r = resolve_all_of(p)
            for k, v in r.items():
                p.setdefault(k, v)
            p.pop("allOf", None)
        base, _ = go_type(p, req_style)
        gt = pointer_type(base, req_style)
        fname = pascal(pname)
        tag = pname + (",omitempty" if req_style else "")
        pd = clean_doc(p.get("description") or "")
        if p.get("enum"):
            allowed = ", ".join(str(e) for e in p["enum"])
            pd = (pd + " " if pd else "") + f"可选值: {allowed}."
        if pd:
            lines.append(f"\t// {fname} {pd}")
        lines.append(f'\t{fname} {gt} `json:"{tag}"`')
    if not props:
        lines.append('\t_ struct{} `json:"-"`')
    lines.append("}")
    return lines


def gen_enum(defname: str) -> list:
    d = DEFS[defname]
    name = type_names[defname]
    values = d["enum"]
    varnames = d.get("x-enum-varnames") or []
    descs = d.get("x-enum-descriptions") or []
    comments = d.get("x-enum-comments") or {}
    is_int = d.get("type") == "integer"
    base = "int" if is_int else "string"

    lines = []
    doc = clean_doc(d.get("description") or "")
    if doc:
        lines.append(f"// {name} {doc}")
    lines.append(f"type {name} {base}")
    lines.append("")
    lines.append("const (")
    for i, v in enumerate(values):
        if i < len(varnames):
            cname = fix_shout(pascal(varnames[i]))
            # 统一加类型前缀, 剥离公共驼峰前缀, 避免裸名/双重前缀常量
            if not cname.startswith(name):
                cname = merge_type_const(name, cname)
        elif not is_int:
            cname = name + pascal(str(v))
        else:
            cname = f"{name}{i}"
        desc = ""
        if i < len(descs):
            desc = clean_doc(str(descs[i]))
        elif not is_int and str(v) in comments:
            desc = clean_doc(comments[str(v)])
        if desc and desc.lower() != cname.lower():
            lines.append(f"\t// {cname} {desc}")
        if is_int:
            lines.append(f"\t{cname} {name} = {v}")
        else:
            lines.append(f'\t{cname} {name} = "{v}"')
    lines.append(")")
    return lines


enum_lines = [GEN_HEADER, "package cnb", ""]
for n in sorted(enum_defs):
    enum_lines += gen_enum(n)
    enum_lines.append("")
model_files["enums_gen.go"] = enum_lines

for n in sorted(DEFS):
    if n in enum_defs:
        continue
    model_files[model_file_for(n)] += gen_struct(n) + [""]

