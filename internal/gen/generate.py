# Spec 加载与分析
# ---------------------------------------------------------------------------

with open(SPEC, encoding="utf-8") as f:
    spec = json.load(f)

DEFS: dict = spec.get("definitions", {})
PATHS: dict = spec.get("paths", {})


def collect_refs(schema, into: set):
    if isinstance(schema, dict):
        if "$ref" in schema:
            n = ref_name(schema)
            if n not in into:
                into.add(n)
                collect_refs(DEFS.get(n, {}), into)
        for k in ("properties", "items", "allOf"):
            collect_refs(schema.get(k), into)
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict):
            collect_refs(ap, into)
    elif isinstance(schema, list):
        for v in schema:
            collect_refs(v, into)


ops = []
for path, item in PATHS.items():
    for method in HTTP_METHODS:
        op = item.get(method)
        if not op:
            continue
        opid = op.get("operationId")
        if not opid:
            print(f"WARN: no operationId for {method.upper()} {path}, skipped",
                  file=sys.stderr)
            continue
        tags = op.get("tags") or ["Misc"]
        ops.append({
            "path": path,
            "method": method.upper(),
            "op": op,
            "opid": opid,
            "tag": tags[0],
            "params": op.get("parameters", []),
        })

opids = [o["opid"] for o in ops]
assert len(opids) == len(set(opids)), "operationId 重复"

# 请求可达 / 响应可达 definition 集合 (传递闭包), 决定字段指针风格:
request_defs: set = set()
for o in ops:
    for p in o["params"]:
        if p.get("in") == "body" and "$ref" in p.get("schema", {}):
            collect_refs(p["schema"], request_defs)

enum_defs = {n for n, d in DEFS.items() if isinstance(d.get("enum"), list)}

# ---------------------------------------------------------------------------
# 类型命名 (全部 definition + 保留名, 全局唯一)
# ---------------------------------------------------------------------------

names = NameRegistry()
for r in ("Client", "Response", "ErrorResponse", "ListOptions", "service",
          "NewClient", "Ptr", "escapePath", "addQuery", "EachPage"):
    names.alloc(r)


def def_go_name(defname: str) -> str:
    segs = defname.split(".")
    for i in range(len(segs) - 1, -1, -1):
        cand = pascal("".join(segs[i:]))
        if cand.lower() not in names._used:
            return names.alloc(cand)
    return names.alloc(pascal(defname.replace(".", "")) + "Def")


type_names = {}
for n in sorted(enum_defs):
    type_names[n] = def_go_name(n)
for n in sorted(DEFS):
    if n not in type_names:
        type_names[n] = def_go_name(n)

# ---------------------------------------------------------------------------
# Go 类型解析
# ---------------------------------------------------------------------------

def resolve_all_of(schema: dict) -> dict:
    merged = {}
    for sub in schema.get("allOf", []):
        if "$ref" in sub:
            sub = DEFS.get(ref_name(sub), {})
        for k, v in sub.items():
            if k == "properties":
                merged.setdefault("properties", {}).update(v)
            elif k == "allOf":
                inner = resolve_all_of(sub)
                merged.setdefault("properties", {}).update(inner.get("properties", {}))
            elif k != "description":
                merged[k] = v
    return merged


def go_scalar(schema: dict) -> str:
    t = schema.get("type")
    if t == "string":
        return "string"
    if t == "integer":
        return "int"
    if t == "number":
        return "float64"
    if t == "boolean":
        return "bool"
    raise ValueError(f"unknown scalar type: {schema}")


def go_type(schema: dict, request_style: bool) -> tuple:
    """schema -> (Go 类型表达式, 是否命名模型引用)."""
    if "$ref" in schema:
        return type_names[ref_name(schema)], True
    if "allOf" in schema:
        r = resolve_all_of(schema)
        if r:
            return go_type(r, request_style)
        return "json.RawMessage", False
    t = schema.get("type")
    if t == "array":
        it, _ = go_type(schema.get("items", {"type": "string"}), request_style)
        return f"[]{it}", False
    if t == "object":
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            vt, _ = go_type(ap, request_style)
            return f"map[string]{vt}", False
        return "map[string]any", False
    if t is None:
        return "json.RawMessage", False
    return go_scalar(schema), False


def pointer_type(go_t: str, request_style: bool) -> str:
    if not request_style:
        return go_t
    if go_t.startswith("[]") or go_t.startswith("map["):
        return go_t
    return "*" + go_t


