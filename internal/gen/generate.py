import os
import re
import subprocess
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SPEC = os.path.join(HERE, "swagger.json")

GEN_HEADER = "// Code generated by internal/gen/generate.py from api.cnb.cool swagger.json. DO NOT EDIT.\n\n"

GO_KEYWORDS = {
    "break", "case", "chan", "const", "continue", "default", "defer", "else",
    "fallthrough", "for", "func", "go", "goto", "if", "import", "interface",
    "map", "package", "range", "return", "select", "struct", "switch", "type",
    "var",
}

HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch")


# ---------------------------------------------------------------------------
# 基础工具
# ---------------------------------------------------------------------------

def pascal(s: str) -> str:
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", s) if p]
    return "".join(p[:1].upper() + p[1:] for p in parts) or "X"


def fix_shout(s: str) -> str:
    """全大写标识符转首字母大写: REPORTER -> Reporter."""
    if len(s) > 1 and s.isupper():
        return s[0] + s[1:].lower()
    return s


_CAMEL_RE = re.compile(r"[A-Z]+(?=[A-Z][a-z])|[A-Z][a-z0-9]*|[a-z0-9]+")


def camel_split(s: str) -> list:
    return _CAMEL_RE.findall(s)


def merge_type_const(type_name: str, varname: str) -> str:
    """生成 '类型名+成员名' 常量名, 剥离 varname 与类型名的驼峰公共前缀.

    例: (ChannelTypeTarget, ChannelTypeInvite) -> ChannelTypeTargetInvite
        (AssetRecordType, AssetSlugImg)         -> AssetRecordTypeSlugImg
    """
    t_segs = camel_split(type_name)
    v_segs = camel_split(varname)
    common = 0
    for a, b in zip(t_segs, v_segs):
        if a.lower() == b.lower():
            common += 1
        else:
            break
    rest = "".join(v_segs[common:])
    if rest:
        return type_name + rest[:1].upper() + rest[1:]
    return type_name


def camel(s: str) -> str:
    p = pascal(s)
    return p[:1].lower() + p[1:]


def clean_doc(s: str) -> str:
    if not s:
        return ""
    return re.sub(r"\s+", " ", s.replace("\r", " ").replace("\n", " ")).strip()


def ref_name(schema: dict) -> str:
    return schema["$ref"].split("/")[-1]


class NameRegistry:
    """包内全局唯一 Go 标识符分配 (大小写不敏感去重)."""

    def __init__(self):
        self._used = set()

    def alloc(self, *candidates: str) -> str:
        for c in candidates:
            if c and c.lower() not in self._used:
                self._used.add(c.lower())
                return c
        base = candidates[-1] or "Name"
        n = 2
        while f"{base}{n}".lower() in self._used:
            n += 1
        name = f"{base}{n}"
        self._used.add(name.lower())
        return name


