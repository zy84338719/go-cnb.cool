"""CNB OpenAPI -> Go SDK 代码生成器.

用法:
    python3 internal/gen/generate.py

读取同目录下的 swagger.json (从 https://api.cnb.cool/swagger.json 下载),
在仓库根目录生成:
    client_gen.go          Client 结构体 + 各 Service 结构体
    enums_gen.go           枚举类型 (string/int, 基于 x-enum-varnames)
    models_*_gen.go        数据模型 (按 definition 前缀分组)
    <tag>_gen.go           各服务的 API 方法
    options_gen.go         查询参数 Options / 内联请求体结构体

生成文件均带 "Code generated" 头; 手写文件: cnb.go / errors.go /
params.go / pagination.go / util.go / *_test.go.
"""
